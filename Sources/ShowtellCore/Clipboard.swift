import Foundation

/// What a clipboard change means while listening: a screenshot, copied text, or nothing for us.
public enum ClipboardChange: Equatable, Sendable {
    case ignore
    case screenshot
    case text(String)

    /// Marks Showtell's own clipboard writes (pasting at the cursor, putting your clipboard back),
    /// so delivery never comes back as a copy.
    public static let ownType = "dev.showtell.own"

    /// Our own writes, and what password managers and clipboard tools mark as not for keeping
    /// (nspasteboard.org).
    static let skippedTypes: Set<String> = [
        ownType, "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ]
    static let imageTypes: Set<String> = ["public.png", "public.tiff"]

    /// `types` are the pasteboard's type identifiers, `string` its plain text if any. Text wins
    /// over a picture: apps copying cells or styled text often add an image of them too, while a
    /// screenshot is only an image.
    public static func classify(types: [String], string: String?) -> ClipboardChange {
        if types.contains(where: skippedTypes.contains) { return .ignore }
        if let string, !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return .text(string) }
        if types.contains(where: imageTypes.contains) { return .screenshot }
        return .ignore
    }
}
